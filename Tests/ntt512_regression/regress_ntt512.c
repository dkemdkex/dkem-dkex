static void unhex(unsigned char *out, const char *hex, size_t n) {
    size_t i;
    for (i = 0; i < n; i++) {
        unsigned int b;
        sscanf(hex + 2 * i, "%2x", &b);
        out[i] = (unsigned char)b;
    }
}

int main(void) {
    unsigned long long pk_len = kem_get_pk_len_bytes(), sk_len = kem_get_sk_len_bytes();
    unsigned long long ct_len = kem_get_ct_len_bytes(), ss_len = kem_get_ss_len_bytes(), len;
    unsigned char *pk = malloc(pk_len), *sk = malloc(sk_len), *ct = malloc(ct_len);
    unsigned char *ss = malloc(ss_len), *ss_dec = malloc(ss_len), *ss_exp = malloc(ss_len);
    unsigned char seed[48];
    size_t i, n = sizeof vectors / sizeof vectors[0];
    int failures = 0;

    if (!pk || !sk || !ct || !ss || !ss_dec || !ss_exp || ss_len != strlen(vectors[0][1]) / 2) {
        printf("setup error\n");
        return 2;
    }
    for (i = 0; i < n; i++) {
        int ok;
        unhex(seed, vectors[i][0], sizeof seed);
        unhex(ss_exp, vectors[i][1], (size_t)ss_len);
        init_random_number(&drng_algorithm, seed, sizeof seed);
        ok = kem_keygen(pk, &len, sk, &len) == 0
          && kem_enc(pk, pk_len, ss, &len, ct, &len) == 0
          && kem_dec(sk, sk_len, ct, ct_len, ss_dec, &len) == 0
          && memcmp(ss, ss_exp, (size_t)ss_len) == 0
          && memcmp(ss_dec, ss_exp, (size_t)ss_len) == 0;
        printf("vector %2u: %s\n", (unsigned)i, ok ? "ok" : "FAIL");
        failures += !ok;
    }
    printf("%s: %d of %u vectors failed\n", failures ? "FAIL" : "PASS", failures, (unsigned)n);
    return failures ? 1 : 0;
}
